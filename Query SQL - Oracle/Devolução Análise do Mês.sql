SELECT
    CASE 
        WHEN GROUPING(TRUNC(DATA_FORMATADA)) = 1 THEN 'TOTAL GERAL'
        ELSE TO_CHAR(TRUNC(DATA_FORMATADA), 'DD/MM/YYYY')
    END AS DATA_DEVOLUCAO,
    COUNT(*) AS QTD,
    SUM(NVL(VLTOTAL_NF, 0)) AS TOTAL_DEVOLUCAO
FROM FRIOPECASBI.BASE_DEVOLUCAO D
WHERE D.DATA_FORMATADA >= DATE '2026-10-01'
  AND D.DATA_FORMATADA < TRUNC(CURRENT_DATE) + 1
GROUP BY ROLLUP(TRUNC(D.DATA_FORMATADA))
ORDER BY TRUNC(D.DATA_FORMATADA) ASC;