WITH CTE_PARAMETROS AS (
    SELECT '2026-10' AS MES_ANO FROM DUAL
),
CTE_VENDAS AS (
    SELECT
        TO_CHAR(V.DATA_FATURAMENTO,'YYYY-MM') AS MES_ANO,
        SUM(NVL(V.VLTOTAL_NF,0)) AS ROB_BRUTA,
        COUNT(DISTINCT V.NUM_NFE_VENDA) AS QTD_NOTAS,
        SUM(NVL(V.PIS_NF,0)+NVL(V.ICMS_NF,0)+NVL(V.COFINS_NF,0)+NVL(V.ICMS_PARTILHA_NF,0)+NVL(V.ICMS_ST_NF,0)+NVL(V.ST_FCP_NF,0)+NVL(V.FCP_NF,0)+NVL(V.ST17_NF,0)) AS TOTAL_IMPOSTOS,
        SUM(NVL(V.CMV_CONTABIL,0)) AS CMV_CONTABIL,
        SUM(NVL(V.BONUSSELLOUT,0)) AS VERBA_SELLOUT,
        -- Desdobramento de Frete (CTE)
        -- CIF (Cost, Insurance and Freight - A FRIOPEÇAS paga o frete, ou seja, Frete Grátis)
        -- FOB (Free On Board - O cliente paga o frete, ou seja, frete consolidado no ato da compra)
        SUM(NVL(V.VALOR_CTE_LIQUIDO,0)) AS CTE_TOTAL,
        SUM(CASE WHEN UPPER(TRIM(V.TIPO_FRETE)) IN ('CIF', 'C', '1') THEN NVL(V.VALOR_CTE_LIQUIDO,0) ELSE 0 END) AS CTE_CIF,
        SUM(CASE WHEN UPPER(TRIM(V.TIPO_FRETE)) IN ('FOB', 'F', '0') THEN NVL(V.VALOR_CTE_LIQUIDO,0) ELSE 0 END) AS CTE_FOB,

        SUM(CASE
            WHEN UPPER(TRIM(V.MARCA)) IN ('WHIRLPOOL','BRASTEMP','CONSUL','EMBRACO')
            THEN NVL(V.VLTOTAL_NF,0)*0.0401
            ELSE 0
        END) AS TAXA_VENDOR,
        SUM(CASE
            WHEN TO_CHAR(V.ID_CENTRO) IN ('1005','1013','1017','1023')
            THEN NVL(V.VLTOTAL_NF,0)*0.0266
            ELSE 0
        END) AS BENEFICIO_FISCAL,
        SUM(CASE
            WHEN TO_CHAR(V.ID_ESC_VENDAS)='1009'
            THEN NVL(V.VLTOTAL_NF,0)*0.0242
            ELSE 0
        END) AS COMISSAO_OFF
    FROM FRIOPECASBI.BASE_VENDAS V
    WHERE NVL(V.ESTORNO,'N')<>'S'
      AND TO_CHAR(V.DATA_FATURAMENTO,'YYYY-MM') IN (SELECT P.MES_ANO FROM CTE_PARAMETROS P)
    GROUP BY TO_CHAR(V.DATA_FATURAMENTO,'YYYY-MM')
),
CTE_DEVOLUCAO AS (
    SELECT
        TO_CHAR(D.DATA_FORMATADA, 'YYYY-MM') AS MES_ANO,
        SUM(NVL(D.VLTOTAL_NF, 0)) AS TOTAL_DEVOLUCAO
    FROM FRIOPECASBI.BASE_DEVOLUCAO D
    WHERE NVL(D.ESTORNO_DEV,'N')<>'S'
      AND TO_CHAR(D.DATA_FORMATADA, 'YYYY-MM') IN (SELECT P.MES_ANO FROM CTE_PARAMETROS P)
    GROUP BY TO_CHAR(D.DATA_FORMATADA, 'YYYY-MM')
),
CTE_COMISSOES AS (
    SELECT
        TO_CHAR(H.DATA,'YYYY-MM') AS MES_ANO,
        SUM(NVL(H.COMISSAO,0)) AS COMISSAO_CONTRATUAL,
        SUM(NVL(H.RB,0)+NVL(H.RBLJTD,0)+NVL(H.PR,0)+NVL(H.PRLJTD,0)+NVL(H.COND_CALC_MKTP,0)+NVL(H.CONDICIONAL_MKTP,0)+NVL(H.CUPOM_MKTP,0)+NVL(H.FRETE_MKTP,0)) AS TOTAL_REBATES
    FROM FRIOPECASBI.HIST_VENDAS H
    WHERE TO_CHAR(H.DATA,'YYYY-MM') IN (SELECT '2026-10' FROM DUAL)
    GROUP BY TO_CHAR(H.DATA,'YYYY-MM')
),
CTE_CONSOLIDADO AS (
    SELECT
        V.MES_ANO,
        V.ROB_BRUTA,
        V.QTD_NOTAS,
        NVL(D.TOTAL_DEVOLUCAO,0) AS DEVOLUCAO,
        V.TOTAL_IMPOSTOS,
        (V.ROB_BRUTA - NVL(D.TOTAL_DEVOLUCAO,0) - V.TOTAL_IMPOSTOS) AS ROL,
        (V.CMV_CONTABIL - V.VERBA_SELLOUT + V.TAXA_VENDOR) AS CUSTO_TOTAL,
        V.BENEFICIO_FISCAL,
        (NVL(C.COMISSAO_CONTRATUAL,0) - NVL(C.TOTAL_REBATES,0) + V.COMISSAO_OFF) AS COMISSAO_LIQUIDA,
        V.CTE_TOTAL,
        V.CTE_CIF,
        V.CTE_FOB
    FROM CTE_VENDAS V
    LEFT JOIN CTE_DEVOLUCAO D ON D.MES_ANO = V.MES_ANO
    LEFT JOIN CTE_COMISSOES C ON C.MES_ANO = V.MES_ANO
),
CTE_DRE_FINAL AS (
    SELECT B.*,
        (B.ROL - B.CUSTO_TOTAL + B.BENEFICIO_FISCAL) AS MARGEM_BRUTA,
        (B.ROL - B.CUSTO_TOTAL + B.BENEFICIO_FISCAL - B.COMISSAO_LIQUIDA - B.CTE_CIF) AS MARGEM_CONTRIBUICAO
    FROM CTE_CONSOLIDADO B
),
CTE_DRE_VERTICAL AS (
    SELECT MES_ANO, 1 AS ORDEM, '(+) 1. RECEITA OPERACIONAL BRUTA' AS CONTA_DRE, ROB_BRUTA AS VALOR, ROL, 'MOEDA' AS TIPO FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 2, '    (-) Devoluções', -DEVOLUCAO, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 3, '    (-) Impostos sobre Vendas', -TOTAL_IMPOSTOS, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 4, '(=) 2. RECEITA OPERACIONAL LÍQUIDA (ROL)', ROL, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 5, '    (-) Custo das Mercadorias (CMV Líquido)', -CUSTO_TOTAL, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 6, '    (+) Benefício Fiscal', BENEFICIO_FISCAL, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 7, '(=) 3. MARGEM BRUTA', MARGEM_BRUTA, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 8, '    (-) Comissões Líquidas', -COMISSAO_LIQUIDA, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 9, '    (-) Logística e Frete (CTE TOTAL)', -CTE_TOTAL, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 9.1, '        [ Frete CIF - Conta Frio Peças ]', -CTE_CIF, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 9.2, '        [ Frete FOB - Conta Cliente ]', -CTE_FOB, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 10, '(=) 4. MARGEM DE CONTRIBUIÇÃO', MARGEM_CONTRIBUICAO, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 11, '    (i) Ticket Médio (ROB / Qtd Notas)', CASE WHEN QTD_NOTAS > 0 THEN ROB_BRUTA/QTD_NOTAS ELSE 0 END, ROL, 'MOEDA' FROM CTE_DRE_FINAL
    UNION ALL
    SELECT MES_ANO, 12, '    (i) % Frete CIF sobre ROL', CASE WHEN ROL <> 0 THEN (CTE_CIF/ROL)*100 ELSE 0 END, ROL, 'PERCENTUAL' FROM CTE_DRE_FINAL
)
SELECT
    MES_ANO AS "PERÍODO",
    CONTA_DRE AS "RUBRICA DRE",
    CASE 
        WHEN TIPO = 'MOEDA' THEN 'R$ '||TO_CHAR(VALOR,'FM999G999G999G990D00','NLS_NUMERIC_CHARACTERS='',.''')
        ELSE TO_CHAR(VALOR,'FM990D00','NLS_NUMERIC_CHARACTERS='',.''')||'%'
    END AS "VALOR",
    CASE
        WHEN ROL<>0 AND TIPO = 'MOEDA' THEN TO_CHAR(ROUND((VALOR/ROL)*100,2),'FM999G990D00','NLS_NUMERIC_CHARACTERS='',.''')||'%'
        ELSE '-'
    END AS "% S/ ROL"
FROM CTE_DRE_VERTICAL
ORDER BY MES_ANO, ORDEM;