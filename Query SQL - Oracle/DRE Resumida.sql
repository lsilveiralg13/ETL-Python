WITH CTE_VENDAS AS (
    SELECT 
        TO_CHAR(V.DATA_FATURAMENTO, 'MM/YYYY') AS MES_ANO,
        UPPER(TO_CHAR(V.DATA_FATURAMENTO, 'FMMONTH', 'NLS_DATE_LANGUAGE=PORTUGUESE')) AS MES_REFERENCIA,
        TO_CHAR(V.DATA_FATURAMENTO, 'YYYYMM') AS ORDEM,
        SUM(NVL(V.VLTOTAL_NF, 0)) AS ROB,
        SUM(NVL(V.PIS_NF,0)+NVL(V.ICMS_NF,0)+NVL(V.COFINS_NF,0)+NVL(V.ICMS_PARTILHA_NF,0)+NVL(V.ICMS_ST_NF,0)+NVL(V.ST_FCP_NF,0)+NVL(V.FCP_NF,0)+NVL(V.ST17_NF,0)) AS IMPOSTOS,
        SUM(CASE WHEN UPPER(TRIM(V.TIPO_FRETE)) IN ('CIF', 'C', '1') THEN NVL(V.VALOR_CTE_LIQUIDO, 0) ELSE 0 END) AS CTE_CIF,
        SUM(CASE WHEN UPPER(TRIM(V.TIPO_FRETE)) IN ('FOB', 'F', '0') THEN NVL(V.VALOR_CTE_LIQUIDO, 0) ELSE 0 END) AS CTE_FOB
    FROM FRIOPECASBI.BASE_VENDAS V
    WHERE NVL(V.ESTORNO, 'N') <> 'S'
    GROUP BY 
        TO_CHAR(V.DATA_FATURAMENTO, 'MM/YYYY'), 
        TO_CHAR(V.DATA_FATURAMENTO, 'FMMONTH', 'NLS_DATE_LANGUAGE=PORTUGUESE'),
        TO_CHAR(V.DATA_FATURAMENTO, 'YYYYMM')
),
CTE_DEVOLUCAO AS (
    SELECT 
        TO_CHAR(D.DATA_FORMATADA, 'MM/YYYY') AS MES_ANO,
        SUM(NVL(D.VLTOTAL_NF, 0)) AS DEVOLUCAO
    FROM FRIOPECASBI.BASE_DEVOLUCAO D
    WHERE NVL(D.ESTORNO_DEV, 'N') <> 'S'
    GROUP BY TO_CHAR(D.DATA_FORMATADA, 'MM/YYYY')
)
SELECT 
    V.MES_REFERENCIA,
    V.MES_ANO,
    'R$ ' || TO_CHAR(V.ROB, 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS ROB,
    'R$ ' || TO_CHAR(NVL(D.DEVOLUCAO, 0), 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS DEVOLUCAO,
    'R$ ' || TO_CHAR((V.ROB - NVL(D.DEVOLUCAO, 0) - V.IMPOSTOS), 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS ROL,
    'R$ ' || TO_CHAR(V.CTE_CIF, 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS CTE_CIF,
    'R$ ' || TO_CHAR(V.CTE_FOB, 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS CTE_FOB,
    'R$ ' || TO_CHAR((V.CTE_CIF + V.CTE_FOB), 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') AS CTE_TOTAL,
    -- Cálculo corrigido do % de Frete sobre a ROL
    TO_CHAR(
        ROUND(
            ((V.CTE_CIF + V.CTE_FOB) / NULLIF(V.ROB - NVL(D.DEVOLUCAO, 0) - V.IMPOSTOS, 0)) * 100, 
            2
        ), 
        'FM990D00', 'NLS_NUMERIC_CHARACTERS='',.'''
    ) || '%' AS PERC_FRETE
FROM CTE_VENDAS V
LEFT JOIN CTE_DEVOLUCAO D ON V.MES_ANO = D.MES_ANO
ORDER BY V.ORDEM DESC;