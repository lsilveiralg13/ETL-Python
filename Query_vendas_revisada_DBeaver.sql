ULTIMA_VENDA_CENTROS AS  (
	SELECT
		
		ID_MATERIAL_PEDIDO,
		ID_CENTRO,
		MAX(DATA_FATURAMENTO) AS ULTIMAVENDA
		FROM FRIOPECASBI.BASE_VENDAS

	WHERE
	
        
 ID_TIPO_DOCUMENTO_PEDIDO = 'ZNOR'
        AND CUSTO_NF > 0
        AND ID_DEPOSITO NOT IN ('0005','0006','0007','0008','0010','0011','0022')
	
    GROUP BY
		ID_MATERIAL_PEDIDO,
		ID_CENTRO
	
 
 
		
),

AJUSTE_ZGOV_CENTROS AS (


	SELECT 
	
	A.ID_MATERIAL_PEDIDO, 
	AVG(NVL(A.CUSTO_NF / NULLIF(A.QTD_FATURADA, 0), 0)) AS CUSTO_MEDIO_ZNOR, 
	A.ID_CENTRO 
	 
	
	FROM FRIOPECASBI.BASE_VENDAS A INNER JOIN ULTIMA_VENDA_CENTROS B ON  A.ID_MATERIAL_PEDIDO = B.ID_MATERIAL_PEDIDO AND A.DATA_FATURAMENTO = B.ULTIMAVENDA AND A.ID_CENTRO = B.ID_CENTRO
	AND A.ID_DEPOSITO NOT IN ('0005','0006','0007','0008','0010','0011','0022')
	AND A.CUSTO_NF > 0
 
	GROUP BY
	A.ID_MATERIAL_PEDIDO, A.ID_CENTRO 
	
	
	 
),

DEPARA AS (
    SELECT DISTINCT
    
        MATERIAL_SAP,
        MATERIAL_ANTIGO
	
		
    FROM FRIOPECASBI.MATERIAL_LEGADO

    WHERE MATERIAL_ANTIGO NOT IN ('nan')
